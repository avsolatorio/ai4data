"""Write a catalogue record for an explainer video as schema.org JSON-LD.

Reads a video card (JSON, see video_card.json) and the caption file it
names, and writes a schema.org VideoObject with the title, description,
duration, publisher, addresses, sources (isBasedOn), captions, transcript,
licence, accessibility features, and the narration disclosure. When the
narration is synthetic, the record carries the disclosure at the end of
the description and the digitalSourceType
CompositeSyntheticDigitalSource, the IPTC code for a composite of several
elements of which at least one is generated by AI.

The duration is taken from the card ("duration_seconds", measured on the
MP4 file, for example with ffprobe). When the card leaves it empty, the
script uses the end of the last caption cue and says so, because the video
runs on for the closing pause. The transcript is the caption text, cue by
cue, when "transcript_from_captions" is true.

Exit status 1 when a required field is missing (title, description,
sources, licence, captions file, narration, and the disclosure for a
synthetic narration), or when the disclosure of a synthetic narration does
not use the word "synthetic".

Usage:
    python video_record.py video_card.json
    python video_record.py video_card.json --out video_record.jsonld

Standard library only.

What this does not check: whether the addresses resolve, whether the
licence is the one the organization applies, or whether the record is
valid for a particular search engine or catalogue. Validate the published
page with the validator of schema.org and read the record once by eye.
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path

TIMING = re.compile(
    r"^((?:\d+:)?\d{2}:\d{2}\.\d{3})\s+-->\s+((?:\d+:)?\d{2}:\d{2}\.\d{3})"
)
REQUIRED = ("title", "description", "sources", "license", "captions", "narration")


def seconds(stamp: str) -> float:
    parts = [float(p) for p in stamp.split(":")]
    while len(parts) < 3:
        parts.insert(0, 0.0)
    return parts[0] * 3600 + parts[1] * 60 + parts[2]


def read_captions(path: Path) -> tuple[float, str]:
    """Return the end of the last cue and the cue text joined as a transcript."""
    end = 0.0
    text: list[str] = []
    in_cue = False
    for line in path.read_text(encoding="utf-8").splitlines():
        m = TIMING.match(line)
        if m:
            end = max(end, seconds(m.group(2)))
            in_cue = True
        elif not line.strip():
            in_cue = False
        elif in_cue:
            text.append(line.strip())
    return end, " ".join(text)


def iso_duration(total: float) -> str:
    whole = math.ceil(total)
    return f"PT{whole // 60}M{whole % 60}S" if whole >= 60 else f"PT{whole}S"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("card", type=Path)
    parser.add_argument("--out", type=Path, help="write the record here")
    args = parser.parse_args(argv)

    card = json.loads(args.card.read_text(encoding="utf-8"))
    problems = [f"the card has no {k}" for k in REQUIRED if not card.get(k)]
    notes: list[str] = []
    captions = args.card.parent / card.get("captions", "")
    if card.get("captions") and not captions.is_file():
        problems.append(f"the captions file {card['captions']} is missing")
    synthetic = card.get("narration") == "synthetic"
    disclosure = card.get("narration_disclosure", "")
    if card.get("narration") not in (None, "", "synthetic", "recorded"):
        problems.append("narration is neither synthetic nor recorded")
    if synthetic and "synthetic" not in disclosure.lower():
        problems.append("the narration is synthetic and the disclosure does not say so")
    if problems:
        for p in problems:
            print(f"problem: {p}")
        print("result: FAIL")
        return 1

    last_cue, transcript = read_captions(captions)
    duration = card.get("duration_seconds")
    if not duration:
        duration = last_cue
        notes.append(
            "duration taken from the last caption cue; measure the MP4 and put it in the card"
        )

    record = {
        "@context": "https://schema.org",
        "@type": "VideoObject",
        "identifier": card.get("id"),
        "name": card["title"],
        "description": f"{card['description']} {disclosure}".strip(),
        "inLanguage": card.get("language"),
        "duration": iso_duration(duration),
        "uploadDate": card.get("upload_date"),
        "publisher": {"@type": "Organization", "name": card.get("publisher")},
        "contentUrl": card.get("content_url"),
        "embedUrl": card.get("embed_url"),
        "thumbnailUrl": card.get("thumbnail_url"),
        "url": card.get("page_url"),
        "isBasedOn": [
            {
                "@type": s.get("type", "CreativeWork"),
                "identifier": s.get("id"),
                "name": s.get("name"),
                "url": s.get("url"),
            }
            for s in card["sources"]
        ],
        "caption": {
            "@type": "MediaObject",
            "contentUrl": card.get("captions_url"),
            "encodingFormat": "text/vtt",
            "inLanguage": card.get("language"),
        },
        "license": card["license"],
        "accessMode": ["auditory", "visual"],
        "accessibilityFeature": ["closedCaptions"],
    }
    if card.get("transcript_from_captions"):
        record["transcript"] = transcript
        record["accessibilityFeature"].append("transcript")
    if synthetic:
        record["digitalSourceType"] = (
            "https://schema.org/CompositeSyntheticDigitalSource"
        )
    record = {k: v for k, v in record.items() if v not in (None, "", [])}

    text = json.dumps(record, indent=2, ensure_ascii=False)
    if args.out:
        args.out.write_text(text + "\n", encoding="utf-8")
        print(f"wrote {args.out.name}: {record['@type']} {record['name']!r}")
        print(
            f"duration {record['duration']}, {len(record['isBasedOn'])} sources,"
            f" transcript of {len(transcript.split())} words,"
            f" narration {card['narration']}"
        )
    else:
        print(text)
    for n in notes:
        print(f"note: {n}")
    print("result: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
